/**
 * Библиотека шаблонов кабинета — Writesonic-подход: карточка → форма → результат.
 * Каждый шаблон знает свои поля и системный промпт; генерация идёт через
 * /api/template (DeepSeek), результат сохраняется в библиотеку контента.
 */

export type TemplateField = {
  id: string;
  label: string;
  placeholder?: string;
  type?: "text" | "textarea" | "select" | "url";
  options?: string[];
  required?: boolean;
  hint?: string;
};

export type TemplateDef = {
  id: string;
  name: string;
  desc: string;
  icon: string;
  group: "Контент" | "Маркетинг" | "SEO" | "E-commerce";
  outputName: string; // подсказка для заголовка результата
  contentType: "статья" | "FAQ" | "пост" | "письмо" | "бриф";
  fields: TemplateField[];
  buildPrompt: (v: Record<string, string>) => string;
};

const F = {
  key: (label = "Ключевой запрос / тема"): TemplateField => ({ id: "key", label, type: "text", required: true, placeholder: "например: установка кондиционеров в Москве" }),
  audience: (): TemplateField => ({ id: "audience", label: "Аудитория", type: "text", placeholder: "например: владельцы квартир 30–50 лет" }),
  tone: (): TemplateField => ({ id: "tone", label: "Тон", type: "select", options: ["деловой", "дружеский", "экспертный", "простой"] }),
  product: (): TemplateField => ({ id: "product", label: "Товар/услуга", type: "textarea", required: true, placeholder: "что продаёте, ключевые характеристики, цена" }),
  cta: (label = "Призыв к действию"): TemplateField => ({ id: "cta", label, type: "text", placeholder: "например: оставьте заявку, замер бесплатный" }),
  notes: (): TemplateField => ({ id: "notes", label: "Пожелания", type: "textarea", placeholder: "что обязательно упомянуть, что исключить" }),
};






