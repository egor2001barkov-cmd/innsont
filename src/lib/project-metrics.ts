// Детерминированный хэш строки для стабильных id (используется в cabinet-pages).
// Генераторы «статистики из хэша домена», жившие здесь раньше, удалены:
// кабинет показывает только реальные замеры и честные пустые состояния.
export function hashStr(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
