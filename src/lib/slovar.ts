export function getTerm(slug: string): Term | undefined {
  const base = TERMS.find((t) => t.slug === slug);
  if (!base) return undefined;
  const extra = TERM_DEEP[slug];
  const extra2 = TERM_DEEP2[slug];
  const extra3 = TERM_DEEP3[slug];
  const extra4 = TERM_DEEP4[slug];
  const extra5 = TERM_DEEP5[slug];
  if (!extra && !extra2 && !extra3 && !extra4 && !extra5) return base;
  return {
    ...base,
    deep: [...(extra?.deep ?? []), ...(extra2?.deep ?? []), ...(extra3?.deep ?? [])],
    faqs: [...base.faqs, ...(extra?.faqs ?? []), ...(extra2?.faqs ?? []), ...(extra3?.faqs ?? []), ...(extra4?.faqs ?? []), ...(extra5?.faqs ?? [])],
  };
}
