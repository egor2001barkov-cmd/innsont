export function getCase(slug: string) {
  return CASES.find((c) => c.slug === slug);
}

export function caseTeaser(slug: string): {
  title: string;
  text: string;
  href: string;
} {
  const item = getCase(slug);
  if (!item) {
    return { title: "Кейс", text: "", href: "/keysy" };
  }
  return {
    title: `${item.company}, ${item.city}`,
    text: item.teaser,
    href: `/keysy/${item.slug}`,
  };
}
