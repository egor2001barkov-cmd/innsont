/**
 * Заголовки и описания для выдачи — правки аудита 26.11.2026 (H1).
 *
 * Применяются поверх данных страниц в построителях метаданных (richMetadata,
 * pageMetadata, termMetadata и generateMetadata статей) и не трогают H1 и текст страницы:
 * исходные title/description в данных остаются, здесь — только то, что видит выдача.
 *
 * Нормы: заголовок — 40–65 знаков вместе с « | INSONT»; описание — 140–160 знаков.
 * Числа — только те, что есть на сайте (тарифы из PLANS, число шаблонов).
 */
export type SeoOverride = { title?: string; description?: string };

/** Заголовок и описание для выдачи с учётом правок: сначала override, иначе данные страницы. */
export function seoOf<T extends { title: string; description: string }>(path: string, base: T): T {
  const o = SEO_OVERRIDES[path.replace(/\/$/, "") || "/"];
  if (!o) return base;
  return { ...base, title: o.title ?? base.title, description: o.description ?? base.description };
}

