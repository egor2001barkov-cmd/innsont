    src = src.replace(MARK, ins.strip("\n") + "\n\n" + MARK, 1)
    # FAQ-добавки в конец тела (перед закрывающим бэктиком)
    BT = chr(96)
    tail = BT + ",\n};"
    end = src.rfind(tail)
    if end == -1:
        print("!! хвост не найден: " + slug); fail += 1; continue
    src = src[:end] + faq_add.strip("\n") + "\n" + src[end:]
    ok += 1
    print(("+" if not dry else "dry+ ") + slug)
    if not dry:
        p.write_text(src, encoding="utf-8")

