for slug, ins in W.items():
    p = next(POSTS.glob(slug + ".ts"), None)
    if p is None or p.parent != POSTS:
        print("!! нет файла " + slug); fail += 1; continue
    src = p.read_text(encoding="utf-8")
    if MARK not in src:
        print("!! маркер: " + slug); fail += 1; continue
    src = src.replace(MARK, ins.strip("\n") + "\n\n" + MARK, 1)
    ok += 1
    print(("+" if not dry else "dry+ ") + slug)
