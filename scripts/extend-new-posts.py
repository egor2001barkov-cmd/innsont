dry = "--apply" not in sys.argv
ok = fail = 0
for slug, w in WORK.items():
    p = next(POSTS.glob(slug + ".ts"), None)
    if p is None or p.parent != POSTS:
        print("!! нет файла " + slug)
        fail += 1
        continue
    src = p.read_text(encoding="utf-8")
    orig = src
    # 1) description
    if w["old_desc"] not in src:
        print("!! desc не найден: " + slug); fail += 1; continue
    src = src.replace(w["old_desc"], w["new_desc"])
    # 2) точечные фиксы
    for old, new in w["fixes"]:
        if old not in src:
            print("!! fix-строка не найдена: " + slug + " :: " + old[:40]); fail += 1; continue
        src = src.replace(old, new)
    # 3) вставка секций
    if MARK not in src:
        print("!! маркер FAQ не найден: " + slug); fail += 1; continue
    src = src.replace(MARK, w["insert"].strip("\n") + "\n\n" + MARK, 1)
    if src != orig:
        ok += 1
        print(("+" if not dry else "dry+ ") + " " + slug)
        if not dry:
            p.write_text(src, encoding="utf-8")
print(f"итог: {ok} изменено, {fail} проблем" + (" (dry-run)" if dry else ""))
